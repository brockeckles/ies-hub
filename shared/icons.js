/**
 * Render an icon as an inline-SVG string.
 * @param {string} name - key in ICONS
 * @param {{size?: number, className?: string, strokeWidth?: number, title?: string}} [opts]
 * @returns {string} SVG markup
 */
export function icon(name, opts = {}) {
  const body = ICONS[name];
  if (!body) throw new Error(`icons.js: unknown icon "${name}"`);
  const { size = 14, className = '', strokeWidth = 2, title = '' } = opts;
  const cls = className ? `hub-icon ${className}` : 'hub-icon';
  const titleEl = title ? `<title>${title}</title>` : '';
  const aria = title ? 'role="img"' : 'aria-hidden="true"';
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" ${aria}>${titleEl}${body}</svg>`;
}
